export function createModule(
  courseId: number,
  title: string,
  position: number | null
) {
  const pos =
    position ??
    (db
      .select({ max: sql<number>`coalesce(max(${modules.position}), 0)` })
      .from(modules)
      .where(eq(modules.courseId, courseId))
      .get()?.max ?? 0) + 1;

  return db
    .insert(modules)
    .values({ courseId, title, position: pos })
    .returning()
    .get();
}

